    //Botón de guardar usuario:
    private void botonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonGuardarActionPerformed
        //Comprobaciones ********************************************************
        //Evitar espacios en blanco:
        if ((this.textoNombre.getText().equals("nombre")) //Si se deja el nombre por default, 
                ||(this.textoNombre.getText().isBlank()) //o se deja el espacio de nombre en blanco,
                ||(this.textoContrasena.getText().equals("jPasswordField1")) //o se deja la contraseña por default,
                ||(this.textoContrasena.getText().isBlank())){//o se deja el espacio de contraseña en blanco:
                    this.textoMensajeError.setText("Complete todos los campos requeridos"); //Entonces, se muestra mensaje de error
                    return; //y se termina la ejecución
        //Evitar nombres de usuario cortos:
        } else if (this.textoNombre.getText().length() < 8){ //Si el nombre de usuario es inferior a 8 caracteres:
            this.textoMensajeError.setText("Ingrese un nombre de usuario de al menos ocho caracteres"); //Entonces, se muestra mensaje de error
            return; //y se termina la ejecución.
        //Evitar contraseñas cortas:
        } else if (this.textoContrasena.getText().length() < 8){ //Si la contraseña es inferior a 8 caracteres:
            this.textoMensajeError.setText("Ingrese una contraseña de al menos ocho caracteres");//Entonces, se muestra mensaje de error
            return; //y se termina la ejecución.
        //Comprobar si el nombre de usuario ya está registrado:
        } else {
                ArrayList<Usuario> usuarios = RegistroDeUsuarios.leerUsuario();
                if (usuarios == null) { //Si ocurrió un error al cargar los usuarios:
                    this.textoMensajeError.setText("No se pudo comprobar si el usuario ya existe"); //Entonces, se muestra mensaje de error
                    return; //y se termina la ejecución.
                }
                for (Usuario usuarioRegistrado : usuarios) {
                    if (usuarioRegistrado.getNombre().equals(this.textoNombre.getText())) {
                        this.textoMensajeError.setText("Ese nombre de usuario ya está registrado"); //Entonces, se muestra mensaje de error
                        return; //y se termina la ejecución.
                    }
                }
            //Fin de las comprobaciones *****************************************
            //Cargar el ArrayList de usuarios, añadir nuevo usuario y guardar la colección en archivo usuarios.dat
            Usuario usuario = new Usuario(textoNombre.getText(), textoContrasena.getText()); //Nuevo usuario
            RegistroDeUsuarios.anadirUsuario(usuario); //
            this.dispose();
            this.menuOriginal.pantallaInicioSesion();
        } 
    }//GEN-LAST:event_botonGuardarActionPerformed
